/** Seed catalogue of travel packages. Read only through the repository in
 *  src/repositories — routes and query helpers never import this directly.
 *
 *  Name, duration, price and group size come from the Unmapped Trips price
 *  list of 27 Oct 2026. Day plans, inclusions, exclusions and highlights are a
 *  first draft of the standard route for each trip, pending the team's review.
 *
 *  None of these carries an `operator`: the trips are run in-house and have no
 *  collected ratings yet. `price` is the amount charged, exactly as on the
 *  price list; the higher `basePrice` is the struck-through list price.
 *  IDs continue after the retired pkg-001…pkg-012 so an enquiry sent from a
 *  stale page can never be filed against a different trip. */
/** Price charged and the struck-through list price. The percentage is derived
 *  (rounded down, so the badge never overstates the saving) rather than typed
 *  by hand beside two numbers it could contradict. */
const pricing = (price: number, listPrice: number) => ({
  price,
  basePrice: listPrice,
  discountPercent: Math.floor(((listPrice - price) * 100) / listPrice),
});

